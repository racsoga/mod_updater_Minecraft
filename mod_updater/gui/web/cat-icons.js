function catIcon(id, size = 20) {
  const map = CAT_ICON_MAPS[id] || CAT_ICON_MAPS.otras;
  let rects = "";
  map.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === "#") rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
  });
  return `<svg class="cat-icon" viewBox="0 0 10 10" width="${size}" height="${size}" aria-hidden="true" shape-rendering="crispEdges" fill="currentColor">${rects}</svg>`;
}
